// - Condição simples com if
// - Estrutura if/else
// - Uso de else if
// - Operadores relacionais (>, <, >=, <=, ===, !==)
// Condição simples
let idade = 18;

if (idade >= 18) {
  console.log("Maior de idade");
}

// If e Else
let nota = 6;

if (nota >= 5) {
  console.log("Aprovado");
} else {
  console.log("Reprovado");
}

// Else if
let hora = 24;

if (hora < 19) {
  console.log("Bom dia");
} else if (hora < 18) {
  console.log("Boa tarde");
} else {
  console.log("Boa noite");
}
